const assert = require('node:assert/strict'), fs = require('node:fs')
const { chromium } = require('@playwright/test')
const fixture = JSON.parse(fs.readFileSync('scratch/chapter-fix/browser-fixture.json', 'utf8'))
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1365, height: 900 } })
    await context.addInitScript(({ token, member }) => { localStorage.setItem('accessToken', token); localStorage.setItem('user', JSON.stringify(member)) }, fixture)
    const page = await context.newPage(), base = 'http://127.0.0.1:3118'
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${base}/student/courses/${fixture.courseId}`)
    await page.getByRole('heading', { name: 'C', exact: true }).waitFor()
    const cLink = page.locator(`a[href='/student/learning/${fixture.lessonIds[2]}']`).first()
    assert.ok(await cLink.isVisible(), 'completed C is a real navigation link in course detail')
    await page.screenshot({ path: 'scratch/chapter-fix/course-detail.png', fullPage: true })
    await cLink.click()
    await page.waitForURL(`**/student/learning/${fixture.lessonIds[2]}`)
    await page.getByRole('heading', { name: 'C', exact: true }).first().waitFor()
    await page.reload()
    await page.getByRole('heading', { name: 'C', exact: true }).first().waitFor()
    assert.equal(new URL(page.url()).pathname, `/student/learning/${fixture.lessonIds[2]}`)
    await page.goto(`${base}/student/learning/${fixture.lessonIds[0]}`)
    await page.getByRole('heading', { name: 'A', exact: true }).first().waitFor()
    // Rapid A -> B -> A uses the actual sidebar switch handler and live APIs.
    const b = page.getByRole('button', { name: /Bài 2: B/ })
    await b.click()
    await page.getByRole('button', { name: /Bài 1: A/ }).click()
    await page.waitForURL(`**/student/learning/${fixture.lessonIds[0]}`)
    await page.getByRole('heading', { name: 'A', exact: true }).first().waitFor()
    await page.screenshot({ path: 'scratch/chapter-fix/learning-A-B-A.png', fullPage: true })
    await page.goto(`${base}/student/learning/${fixture.lessonIds[3]}`)
    await page.getByText(/Bạn cần hoàn thành video trước đó/).first().waitFor()
    assert.equal(errors.length, 0, errors.join('\n'))
    const guest = await browser.newContext({ viewport: { width: 1365, height: 900 } })
    const statsPage = await guest.newPage()
    await statsPage.goto(`${base}/leaderboard?group=CHAPTER&periodType=ACTUAL_TERM`)
    await statsPage.getByRole('heading', { name: 'Thống kê nhiệm kỳ thực tế', exact: true }).waitFor()
    await statsPage.screenshot({ path: 'scratch/chapter-fix/actual-term-statistics.png', fullPage: true })
    console.log('PASS browser: MEMBER course C link, direct C, F5, rapid A-B-A, direct unopened D denied, Guest actual-term statistics, no page errors.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
